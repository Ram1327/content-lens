"use client";

import { useState } from "react";
import type { DetectTextResponse } from "@content-lens/shared-types";
import { VerdictBadge } from "./VerdictBadge";
import { ConfidenceBar } from "./ConfidenceBar";
import { Button } from "@/components/ui/button";
import { Check, Copy, RotateCcw, Cpu, FileText } from "lucide-react";
import { formatConfidence } from "@/lib/utils";

interface ResultCardProps {
  result: DetectTextResponse & { analyzedText?: string };
  onReset: () => void;
}

export function ResultCard({ result, onReset }: ResultCardProps) {
  const [copied, setCopied] = useState(false);

  const getExplanation = () => {
    switch (result.verdict) {
      case "ai_generated":
        return "This text displays repetitive syntactic structures, vocabulary distributions, and low burstiness commonly generated by AI language models.";
      case "human":
        return "This text demonstrates organic variation in sentence length, natural phrasing, and idiosyncratic nuances typical of authentic human writing.";
      case "uncertain":
      default:
        return "The text contains a blend of signals or subtle stylistic markers where neither AI generation nor pure human writing could be confirmed with high confidence.";
    }
  };

  const copySummary = () => {
    const text = `ContentLens AI Scan Result:\nVerdict: ${result.verdict}\nConfidence: ${formatConfidence(
      result.confidence
    )}\nModel: ${result.model_version}`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="rounded-2xl border border-border bg-card p-6 shadow-sm sm:p-8 space-y-6 animate-in fade-in-50 duration-500">
      {/* Header with Verdict & Model Version */}
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-border/60 pb-5">
        <div>
          <span className="text-xs font-semibold uppercase tracking-wider text-muted-foreground block mb-1.5">
            Analysis Result
          </span>
          <VerdictBadge verdict={result.verdict} size="lg" />
        </div>

        <div className="flex items-center gap-1.5 rounded-full border border-border/80 bg-muted/60 px-3 py-1 text-xs text-muted-foreground">
          <Cpu className="size-3.5 text-primary" />
          <span className="font-mono">{result.model_version}</span>
        </div>
      </div>

      {/* Confidence Bar & Percentage */}
      <div className="rounded-xl bg-muted/30 p-4 border border-border/40">
        <ConfidenceBar confidence={result.confidence} verdict={result.verdict} />
      </div>

      {/* Detailed Analysis Explanation */}
      <div className="rounded-xl border border-border/60 bg-muted/20 p-4 space-y-2">
        <h4 className="text-xs font-semibold uppercase tracking-wider text-foreground">
          Evaluation Summary
        </h4>
        <p className="text-sm leading-relaxed text-muted-foreground">{getExplanation()}</p>
      </div>

      {/* Analyzed Text Snippet Preview */}
      {result.analyzedText && (
        <div className="space-y-2">
          <div className="flex items-center gap-1.5 text-xs font-medium text-muted-foreground">
            <FileText className="size-3.5" />
            <span>Scanned Text ({result.analyzedText.length} characters)</span>
          </div>
          <div className="max-h-28 overflow-y-auto rounded-lg border border-border/50 bg-muted/40 p-3 text-xs leading-relaxed text-muted-foreground font-mono">
            {result.analyzedText}
          </div>
        </div>
      )}

      {/* Action Buttons */}
      <div className="flex flex-wrap items-center justify-between gap-3 border-t border-border/60 pt-5">
        <Button
          variant="outline"
          size="sm"
          onClick={copySummary}
          className="gap-1.5 text-xs"
        >
          {copied ? <Check className="size-3.5 text-emerald-600" /> : <Copy className="size-3.5" />}
          <span>{copied ? "Copied" : "Copy Result"}</span>
        </Button>

        <Button
          onClick={onReset}
          size="sm"
          className="gap-1.5 text-xs font-medium"
        >
          <RotateCcw className="size-3.5" />
          <span>Scan Another Text</span>
        </Button>
      </div>
    </div>
  );
}
